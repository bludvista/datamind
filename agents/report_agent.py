import os
from dotenv import load_dotenv
from datetime import datetime

load_dotenv()

def run_report_agent(insights_results: dict) -> str:
    print("🤖 Agent 5 [Report Writer] — Starting...")

    insights = insights_results["insights"]
    eda = insights_results["eda_results"]

    html_content = f"""
<!DOCTYPE html>
<html>
<head>
    <title>DataMind HR Attrition Report</title>
    <style>
        body {{ font-family: Arial, sans-serif; max-width: 900px; margin: 40px auto; padding: 20px; color: #333; }}
        h1 {{ color: #2c3e50; border-bottom: 3px solid #3498db; padding-bottom: 10px; }}
        h2 {{ color: #2980b9; margin-top: 30px; }}
        .stat-box {{ background: #f0f4f8; border-left: 4px solid #3498db; padding: 15px; margin: 10px 0; border-radius: 4px; }}
        .insights {{ background: #fafafa; padding: 20px; border-radius: 8px; border: 1px solid #ddd; white-space: pre-wrap; }}
        .footer {{ text-align: center; color: #999; margin-top: 40px; font-size: 12px; }}
        table {{ width: 100%; border-collapse: collapse; margin: 15px 0; }}
        th {{ background: #3498db; color: white; padding: 10px; }}
        td {{ padding: 10px; border-bottom: 1px solid #eee; }}
        tr:hover {{ background: #f5f5f5; }}
    </style>
</head>
<body>
    <h1>📊 DataMind — HR Attrition Analysis Report</h1>
    <p><strong>Generated:</strong> {datetime.now().strftime("%B %d, %Y at %I:%M %p")}</p>
    <p><strong>Dataset:</strong> IBM HR Employee Attrition</p>

    <h2>📈 Key Statistics</h2>
    <div class="stat-box">Overall Attrition Rate: <strong>{eda['attrition_rate']}%</strong></div>
    <div class="stat-box">Average Age (Left): <strong>{eda['avg_age_left']}</strong></div>
    <div class="stat-box">Average Age (Stayed): <strong>{eda['avg_age_stayed']}</strong></div>

    <h2>🏢 Attrition by Department</h2>
    <table>
        <tr><th>Department</th><th>Attrition Rate (%)</th></tr>
        {"".join([f"<tr><td>{dept}</td><td>{rate}%</td></tr>" for dept, rate in eda['attrition_by_department'].items()])}
    </table>

    <h2>🤖 AI-Generated Insights</h2>
    <div class="insights">{insights}</div>

    <div class="footer">Generated by DataMind Agentic AI System</div>
</body>
</html>
"""

    os.makedirs("reports", exist_ok=True)
    filename = f"reports/hr_attrition_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.html"
    with open(filename, "w", encoding="utf-8") as f:
        f.write(html_content)

    print(f"✅ Agent 5 Done! Report saved as: {filename}")
    print(f"📂 Open it in your browser to view the full report!")
    return filename


